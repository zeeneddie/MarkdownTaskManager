/**
 * Task Generation Types for Self-Questioning Agents
 * Week 23-24 Implementation
 *
 * Self-Questioning allows agents to generate their own training tasks
 * based on identified skill gaps, failures, and unexplored areas.
 */

// =============================================================================
// Enums
// =============================================================================

export enum GeneratedTaskType {
  /** Retry a previously failed task with adjusted approach */
  FAILURE_RETRY = 'FAILURE_RETRY',
  /** Test edge cases derived from successful patterns */
  EDGE_CASE_TEST = 'EDGE_CASE_TEST',
  /** Expand agent skills into new areas */
  SKILL_EXPANSION = 'SKILL_EXPANSION',
  /** Generate validation test cases */
  VALIDATION_TEST = 'VALIDATION_TEST',
  /** Practice applying known patterns */
  PATTERN_PRACTICE = 'PATTERN_PRACTICE',
  /** Explore unexplored areas of the codebase */
  EXPLORATION = 'EXPLORATION'
}

export enum TaskDifficulty {
  EASY = 'EASY',
  MEDIUM = 'MEDIUM',
  HARD = 'HARD'
}

export enum TaskStatus {
  PENDING = 'PENDING',
  IN_PROGRESS = 'IN_PROGRESS',
  COMPLETED = 'COMPLETED',
  FAILED = 'FAILED',
  SKIPPED = 'SKIPPED'
}

export enum TaskSource {
  /** Generated by the agent itself */
  AGENT = 'AGENT',
  /** Generated by the system based on attribution */
  ATTRIBUTION = 'ATTRIBUTION',
  /** Generated from validation failures */
  VALIDATION = 'VALIDATION',
  /** Generated from environment exploration */
  EXPLORATION = 'EXPLORATION'
}

export enum SkillGapSeverity {
  CRITICAL = 'CRITICAL',
  IMPORTANT = 'IMPORTANT',
  MINOR = 'MINOR'
}

// =============================================================================
// Core Interfaces
// =============================================================================

/**
 * A scenario describing the context for a training task
 */
export interface TaskScenario {
  /** Human-readable description of the scenario */
  description: string;
  /** Contextual data for the task */
  context: Record<string, any>;
  /** Constraints that must be satisfied */
  constraints: string[];
  /** Criteria for successful completion */
  successCriteria: string[];
  /** Optional: Related patterns to apply */
  relatedPatterns?: string[];
  /** Optional: Files or areas to focus on */
  focusAreas?: string[];
}

/**
 * Expected outcome for a training task
 */
export interface ExpectedOutcome {
  /** What should the agent learn from this task? */
  learningObjective: string;
  /** Expected success rate (0-1) */
  expectedSuccessRate: number;
  /** Skills that should improve */
  targetSkills: string[];
  /** Metrics to measure improvement */
  improvementMetrics: string[];
}

/**
 * A training task generated by or for an agent
 */
export interface TrainingTask {
  id: string;
  agentId: string;
  agentName: string;
  taskType: GeneratedTaskType;
  scenario: TaskScenario;
  expectedOutcome: ExpectedOutcome;
  difficulty: TaskDifficulty;
  source: TaskSource;
  status: TaskStatus;

  /** Link to attribution that triggered this task (if any) */
  parentAttributionId?: string;
  /** Link to validation failure that triggered this task */
  parentValidationId?: string;
  /** Link to skill gap this addresses */
  skillGapId?: string;

  /** Priority score (higher = more important) */
  priority: number;
  /** Estimated time to complete (ms) */
  estimatedDuration: number;

  /** Timestamps */
  createdAt: Date;
  startedAt?: Date;
  completedAt?: Date;

  /** Execution metadata */
  executionAttempts: number;
  maxAttempts: number;
}

/**
 * Result of executing a training task
 */
export interface TrainingTaskResult {
  taskId: string;
  agentId: string;
  success: boolean;

  /** Actual outcome vs expected */
  actualOutcome: {
    learningAchieved: string[];
    skillsImproved: string[];
    unexpectedLearnings: string[];
  };

  /** Performance metrics */
  metrics: {
    duration: number;
    attempts: number;
    validationPassed: boolean;
    confidenceScore: number;
  };

  /** Lessons learned */
  lessons: TrainingLesson[];

  /** Generated follow-up tasks (if any) */
  followUpTasks: Partial<TrainingTask>[];

  /** Link to attribution for this result */
  attributionId?: string;

  completedAt: Date;
}

/**
 * A lesson learned from training
 */
export interface TrainingLesson {
  lessonId: string;
  type: 'SUCCESS' | 'FAILURE' | 'INSIGHT';
  description: string;
  applicableScenarios: string[];
  confidence: number;
}

// =============================================================================
// Skill Gap Tracking
// =============================================================================

/**
 * An identified gap in agent skills
 */
export interface SkillGap {
  id: string;
  agentId: string;
  agentName: string;

  /** Description of the skill gap */
  description: string;
  /** Area/domain of the gap */
  area: string;
  /** How severe is this gap? */
  severity: SkillGapSeverity;

  /** Evidence supporting this gap */
  evidence: SkillGapEvidence[];

  /** Has this gap been addressed? */
  addressed: boolean;
  /** Training tasks generated to address this gap */
  generatedTaskIds: string[];

  /** When was this gap identified? */
  identifiedAt: Date;
  /** When was this gap addressed? */
  addressedAt?: Date;
}

/**
 * Evidence supporting a skill gap
 */
export interface SkillGapEvidence {
  type: 'ATTRIBUTION_FAILURE' | 'VALIDATION_FAILURE' | 'LOW_CONFIDENCE' | 'PATTERN_MISSING';
  sourceId: string;
  description: string;
  timestamp: Date;
}

// =============================================================================
// Environment Exploration
// =============================================================================

/**
 * A target area for environment exploration
 */
export interface ExplorationTarget {
  id: string;
  /** Type of target */
  type: 'CODEBASE_AREA' | 'PATTERN' | 'TECHNOLOGY' | 'WORKFLOW';
  /** Name/identifier of the target */
  name: string;
  /** Why is this worth exploring? */
  reason: string;
  /** Estimated learning value (0-1) */
  learningValue: number;
  /** Has this been explored? */
  explored: boolean;
  /** Related skill gaps */
  relatedSkillGaps: string[];
}

/**
 * Comparison between projects for learning
 */
export interface ProjectComparison {
  currentProject: string;
  similarProject: string;
  similarityScore: number;
  differences: {
    area: string;
    currentApproach: string;
    alternativeApproach: string;
    potentialImprovement: string;
  }[];
  suggestedTasks: Partial<TrainingTask>[];
}

