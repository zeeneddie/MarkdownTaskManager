// =============================================================================
// Metrics & Progress
// =============================================================================

/**
 * Improvement metrics for an agent
 */
export interface ImprovementMetrics {
  agentId: string;
  period: {
    start: Date;
    end: Date;
  };

  /** Task completion metrics */
  tasksGenerated: number;
  tasksCompleted: number;
  tasksSuccessful: number;
  tasksFailed: number;

  /** Learning metrics */
  skillGapsIdentified: number;
  skillGapsAddressed: number;
  lessonsLearned: number;
  patternsDiscovered: number;

  /** Performance improvements */
  successRateChange: number;  // -1 to 1 (e.g., 0.15 = +15%)
  confidenceChange: number;
  estimationAccuracyChange: number;

  /** Trend indicator */
  trend: 'IMPROVING' | 'STABLE' | 'DECLINING';
}

/**
 * Training session summary
 */
export interface TrainingSession {
  sessionId: string;
  agentId: string;
  startedAt: Date;
  completedAt?: Date;

  /** Tasks in this session */
  tasks: TrainingTask[];
  results: TrainingTaskResult[];

  /** Session outcomes */
  skillGapsAddressed: string[];
  newSkillGapsIdentified: string[];
  overallSuccess: boolean;

  /** Metrics delta */
  metricsBeforeSession: Partial<ImprovementMetrics>;
  metricsAfterSession: Partial<ImprovementMetrics>;
}

// =============================================================================
// API Request/Response Types
// =============================================================================

export interface GenerateTasksRequest {
  agentId: string;
  /** Override default strategy */
  strategy?: Partial<GenerationStrategy>;
  /** Focus on specific skill gaps */
  targetSkillGaps?: string[];
  /** Maximum number of tasks to generate */
  maxTasks?: number;
}

export interface GenerateTasksResponse {
  tasks: TrainingTask[];
  skillGapsTargeted: SkillGap[];
  estimatedTrainingTime: number;
}

export interface ExecuteTaskRequest {
  taskId: string;
  /** Override max attempts */
  maxAttempts?: number;
}

export interface ExecuteTaskResponse {
  result: TrainingTaskResult;
  experienceUpdated: boolean;
  followUpTasksGenerated: number;
}

export interface GetSkillGapsRequest {
  agentId: string;
  /** Filter by severity */
  minSeverity?: SkillGapSeverity;
  /** Include addressed gaps */
  includeAddressed?: boolean;
}

export interface GetSkillGapsResponse {
  skillGaps: SkillGap[];
  totalGaps: number;
  criticalGaps: number;
  addressedGaps: number;
}

export interface GetMetricsRequest {
  agentId: string;
  periodDays?: number;
}

export interface GetMetricsResponse {
  metrics: ImprovementMetrics;
  historicalMetrics: ImprovementMetrics[];
}
